import fs from 'node:fs';
const read=(file)=>fs.readFileSync(file,'utf8');
const fail=(message)=>{console.error(`FAIL: ${message}`);process.exit(1)};
const expect=(condition,message)=>{if(!condition)fail(message);console.log(`PASS: ${message}`)};
const entry=read('index.src.html');
const app=read('src/main-v2.jsx');
const distHtml=read('dist/index.html');
const walk=(dir)=>fs.readdirSync(dir,{withFileTypes:true}).flatMap(e=>{const p=`${dir}/${e.name}`;return e.isDirectory()?walk(p):[p]});
const distFiles=walk('dist');
const distText=distFiles.filter(f=>/\.(js|html|css|mjs)$/.test(f)).map(read).join('\n');
const proxyMarker=['getjobready-ai-proxy','mnijhara','workers','dev'].join('.');
expect(entry.includes('/src/native-entry.jsx')||entry.includes('/src/main-v2.jsx'),'source entry loads the native React product');
expect(!entry.includes('api-bridge.js'),'source entry does not load the legacy API bridge');
expect(!entry.includes('cv-improvement-flow.js'),'legacy CV overlay is not shipped');
expect(!entry.includes('audio-auto.js'),'legacy audio bridge is not shipped');
expect(app.includes('function CVStudio'),'source contains native CV improvement studio');
expect(app.includes('rewrittenBullets'),'source contains AI-generated editable CV improvements');
expect(app.includes('Save & continue to live interview'),'source contains the CV-save interview gate');
expect(app.includes('SpeechRecognition'),'source contains browser voice capture');
expect(app.includes('Live transcript'),'source contains visible transcript UI');
expect(app.includes('disableWorker:true'),'source contains worker-independent PDF parsing');
expect(app.includes("post('/api/analyze'"),'source sends CV analysis through the server API');
expect(app.includes("post('/api/interview-turn'"),'source sends interview turns through the server API');
expect(!app.includes(proxyMarker),'source does not expose the AI proxy to the browser');
expect(distHtml.includes('/assets/')||distHtml.includes('index-'),'production HTML references built assets');
expect(distText.includes('GetJobReady'),'production bundle contains the native product');
expect(distText.includes('/api/interview-turn'),'production bundle contains the native interview API flow');
expect(distText.includes('captured automatically'),'production bundle contains the live transcript capture UX');
expect(!distText.includes(proxyMarker),'production bundle does not expose the AI proxy endpoint');
expect(distText.includes('How it works'),'production bundle contains the working How it works experience');
expect(distText.includes('Summer Internship')&&distText.includes('Full-time Job'),'production bundle contains both career tracks');
expect(distText.includes('General CV')&&distText.includes('CV + specific JD'),'production bundle contains both preparation modes');
expect(distText.includes('Improve your CV first'),'production bundle contains the CV improvement gate');
expect(distText.includes('Save & continue to live interview'),'production bundle contains the interview save gate');
expect(distText.includes('Live transcript'),'production bundle contains transcript UI');
expect(distFiles.some(f=>f.endsWith('/pdf.worker.mjs')),'production bundle contains the stable PDF worker');
console.log('GetJobReady production/source parity verification passed.');
